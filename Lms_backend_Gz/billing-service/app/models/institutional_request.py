"""Institutional course purchase requests, quotations, payments, and approvals."""

from datetime import datetime
from typing import Any

from sqlalchemy import BigInteger, ForeignKey, Index, Integer, String, Text
from sqlalchemy.orm import Mapped, mapped_column

from app.db.base import Base, TimestampMixin, UUIDPrimaryKeyMixin
from app.db.types import JSONType


class InstitutionalPurchaseRequest(UUIDPrimaryKeyMixin, TimestampMixin, Base):
    """Institutional multi-course bulk purchase requests and quotation workflows."""

    __tablename__ = "institutional_purchase_requests"

    public_id: Mapped[int] = mapped_column(BigInteger, unique=True, index=True)
    organization_id: Mapped[int] = mapped_column(BigInteger, index=True)
    institution_name: Mapped[str] = mapped_column(String(255))
    institution_code: Mapped[str | None] = mapped_column(String(100), nullable=True)
    contact_person: Mapped[str] = mapped_column(String(255))
    contact_email: Mapped[str] = mapped_column(String(255))
    contact_phone: Mapped[str | None] = mapped_column(String(50), nullable=True)

    # Requested package configuration
    requested_courses: Mapped[list[dict[str, Any]]] = mapped_column(JSONType, default=list)
    seats_requested: Mapped[int] = mapped_column(Integer)
    duration_days_requested: Mapped[int] = mapped_column(Integer)
    starts_at_requested: Mapped[datetime | None] = mapped_column(nullable=True)
    ends_at_requested: Mapped[datetime | None] = mapped_column(nullable=True)
    calculation_breakdown: Mapped[dict[str, Any] | None] = mapped_column(JSONType, nullable=True)
    quotation_versions: Mapped[list[dict[str, Any]]] = mapped_column(JSONType, default=list)
    message: Mapped[str | None] = mapped_column(Text, nullable=True)

    # Status: pending | quoted | accepted | rejected | modification_requested | paid | approved | expired
    status: Mapped[str] = mapped_column(String(50), default="pending", index=True)

    # Quotation generated by Admin
    quotation: Mapped[dict[str, Any] | None] = mapped_column(JSONType, nullable=True)
    quoted_by: Mapped[int | None] = mapped_column(BigInteger, nullable=True)
    modification_notes: Mapped[str | None] = mapped_column(Text, nullable=True)

    # Payment details from gateway
    payment_info: Mapped[dict[str, Any] | None] = mapped_column(JSONType, nullable=True)

    # Admin approval & activation
    approved_by: Mapped[int | None] = mapped_column(BigInteger, nullable=True)
    approved_at: Mapped[datetime | None] = mapped_column(nullable=True)
    package_starts_at: Mapped[datetime | None] = mapped_column(nullable=True)
    package_ends_at: Mapped[datetime | None] = mapped_column(nullable=True)

    created_by: Mapped[int] = mapped_column(BigInteger)

    __table_args__ = (
        Index("ix_inst_req_org_status", "organization_id", "status"),
    )
