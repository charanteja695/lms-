"""Write .env.example (local) and .env.docker.example (docker compose) from app/core/config.py.

Every setting lives in the env file, so behaviour changes by editing .env, never code:

    python scripts/generate_env_example.py
    cp .env.example .env                 # local run
    cp .env.docker.example .env.docker   # docker compose

tests/unit/test_env_example.py fails if a setting is added to config.py without regenerating.
"""

import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from pydantic import SecretStr  # noqa: E402

from app.core.config import Settings  # noqa: E402

HEADER = """# ============================================================================================
# {title}
# Generated by scripts/generate_env_example.py from app/core/config.py. Copy to {target} and edit
# values there; never commit real secrets. Staging/production refuse to start with development values.
# ============================================================================================
"""

# Values that must be replaced per environment (shown instead of the development default).
PLACEHOLDERS = {
    "JWT_SECRET_KEY": "insecure-dev-jwt-secret-change-me-000000000",
    "TOKEN_HASH_SECRET": "insecure-dev-token-hash-secret-change-me-0",
}
LOCAL_OVERRIDES = {
    "ENVIRONMENT": "local",
    "LOG_JSON": "false",
    "CORS_ORIGINS": '["http://localhost:3000"]',
    "REFRESH_COOKIE_SECURE": "false",
    # The code default depends on the machine's CPU count; the example uses a fixed value.
    "PASSWORD_HASH_CONCURRENCY": "8",
    # RS256 everywhere but tests: every other service verifies tokens with the public key (JWKS). Keys come from
    # python scripts/generate_jwt_keys.py keys
    "JWT_ALGORITHM": "RS256",
    "JWT_PRIVATE_KEY_FILE": "keys/jwt_private.pem",
    "JWT_PUBLIC_KEY_FILE": "keys/jwt_public.pem",
}
DOCKER_OVERRIDES = {
    **LOCAL_OVERRIDES,
    "LOG_JSON": "true",
    "DATABASE_URL": "postgresql+asyncpg://lms:lms@postgres:5432/lms_user_management",
    "REDIS_URL": "redis://redis:6379/0",
    "JOB_STORAGE_DIR": "/app/var/jobs",
    "JWT_PRIVATE_KEY_FILE": "/app/keys/jwt_private.pem",
    "JWT_PUBLIC_KEY_FILE": "/app/keys/jwt_public.pem",
}


def _format(value: object) -> str:
    if isinstance(value, SecretStr):
        value = value.get_secret_value()
    if value is None:
        return ""
    if isinstance(value, bool):
        return str(value).lower()
    if isinstance(value, list | dict):
        return json.dumps(value, separators=(",", ":"))
    return str(value)


def render(overrides: dict[str, str], title: str, target: str) -> str:
    source = (ROOT / "app/core/config.py").read_text(encoding="utf-8").splitlines()
    fields = Settings.model_fields
    lines = [HEADER.format(title=title, target=target)]
    comments: list[str] = []
    for raw in source:
        line = raw.strip()
        section = re.match(r"^# --- (.+?) ---$", line)
        if section:
            lines.append(f"\n# --- {section.group(1)} ---")
            comments = []
            continue
        if line.startswith("#"):
            comments.append(line)
            continue
        field = re.match(r"^([A-Z][A-Z0-9_]+)\s*:", line)
        if field and field.group(1) in fields:
            name = field.group(1)
            info = fields[name]
            lines.extend(comments)
            if info.description:
                lines.append(f"# {info.description}")
            default = info.get_default(call_default_factory=True)
            value = overrides.get(name, PLACEHOLDERS.get(name, _format(default)))
            prefix = "# " if default is None and name not in overrides else ""
            lines.append(f"{prefix}{name}={value}")
        comments = []
    return "\n".join(lines).rstrip() + "\n"


def main() -> None:
    (ROOT / ".env.example").write_text(
        render(LOCAL_OVERRIDES, "user-management: local settings", ".env"), encoding="utf-8"
    )
    (ROOT / ".env.docker.example").write_text(
        render(DOCKER_OVERRIDES, "user-management: docker compose settings", ".env.docker"), encoding="utf-8"
    )
    print("Wrote .env.example and .env.docker.example")


if __name__ == "__main__":
    main()
